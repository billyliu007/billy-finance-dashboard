const DEFAULT_LANGUAGE = 'en';
const STORAGE_KEY = 'app_language';

export function getStoredLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'zh' || stored === 'en') return stored;
  } catch {
    // ignore
  }
  return DEFAULT_LANGUAGE;
}

export function setStoredLanguage(lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // ignore
  }
}

/**
 * Get a nested value by dot path, e.g. 'nav.netWorth' -> translations[lang].nav.netWorth
 */
function getNested(obj, path) {
  const parts = String(path).split('.');
  let current = obj;
  for (const part of parts) {
    current = current?.[part];
  }
  return typeof current === 'string' ? current : path;
}

/**
 * @param {string} lang - 'en' | 'zh'
 * @param {string} key - e.g. 'nav.netWorth' or 'modals.removeCashConfirm'
 * @param {Record<string, string>} [vars] - e.g. { name: 'DBS' } for "Remove \"DBS\"?"
 * @returns {string}
 */
export function translate(lang, key, vars = {}) {
  const text = getNested(translations[lang] || translations.en, key);
  if (!vars || Object.keys(vars).length === 0) return text;
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v)),
    text
  );
}
